# ---------------- Database ----------------
def init_db():
    conn = sqlite3.connect(DB_PATH, check_same_thread=False)
    c = conn.cursor()

    c.execute(
        """CREATE TABLE IF NOT EXISTS users(
        id TEXT PRIMARY KEY,
        email TEXT UNIQUE,
        password_hash TEXT,
        full_name TEXT,
        phone TEXT,
        account TEXT,
        balance REAL DEFAULT 0.0,
        settings TEXT
    )"""
    )

    c.execute(
        """CREATE TABLE IF NOT EXISTS deposits(
        id TEXT PRIMARY KEY,
        user_id TEXT,
        name TEXT,
        amount REAL,
        rate REAL,
        opened TEXT,
        ends TEXT,
        active INTEGER,
        FOREIGN KEY(user_id) REFERENCES users(id)
    )"""
    )

    c.execute(
        """CREATE TABLE IF NOT EXISTS ops(
        id TEXT PRIMARY KEY,
        user_id TEXT,
        date TEXT,
        type TEXT,
        amount REAL,
        currency TEXT,
        title TEXT,
        details TEXT,
        FOREIGN KEY(user_id) REFERENCES users(id)
    )"""
    )

    conn.commit()
    return conn


DB = init_db()

# ---------------- Helpers ----------------
def now_ts() -> str:
    return datetime.datetime.now().isoformat(sep=" ", timespec="seconds")


def hash_password(p: str) -> str:
    return hashlib.sha256(p.encode("utf-8")).hexdigest()


def validate_password(email: str, password: str) -> Tuple[bool, str]:
    if len(password) < 8:
        return False, "Пароль должен содержать минимум 8 символов."
    if password.lower() == email.lower():
        return False, "Пароль не должен совпадать с email."
    if not re.search(r"[A-ZА-ЯЁ]", password):
        return False, "Пароль должен содержать хотя бы одну заглавную букву."
    if not re.search(r"[a-zа-яё]", password):
        return False, "Пароль должен содержать хотя бы одну строчную букву."
    if not re.search(r"\d", password):
        return False, "Пароль должен содержать хотя бы одну цифру."
    if not re.search(r"[!@#$%^&*]", password):
        return False, "Пароль должен содержать хотя бы один специальный символ (!@#$%^&*)."
    return True, ""


def validate_email(email: str) -> Tuple[bool, str]:
    email = (email or "").strip().lower()
    if not email or "@" not in email:
        return False, "Введите корректный email."
    parts = email.split("@")
    if len(parts) != 2 or not parts[0] or not parts[1]:
        return False, "Введите корректный email."
    return True, ""


def validate_phone(phone: str) -> Tuple[bool, str]:
    phone = (phone or "").strip()
    if phone and not re.fullmatch(r"[\d\+\-\(\)\s]{6,20}", phone):
        return False, "Телефон указан в неверном формате"
    return True, ""


def generate_account_number() -> str:
    s = "".join(str(random.randint(0, 9)) for _ in range(16))
    return " ".join([s[i:i + 4] for i in range(0, 16, 4)])


def human_op_type(op_type: str) -> str:
    mapping = {
        "income": "Пополнение",
        "expense": "Расход",
        "transfer": "Перевод",
        "deposit_open": "Открытие вклада",
        "deposit_close": "Закрытие вклада",
        "deposit_interest": "Начисление процентов",
    }
    return mapping.get(op_type, op_type)


def safe_float(value, default=None):
    try:
        return float(value)
    except:
        return default


def safe_date(date_str: str):
    try:
        return datetime.datetime.strptime(date_str, "%Y-%m-%d").date()
    except:
        return None


# ---------------- DB operations ----------------
def user_create(email: str, password: str, full_name: str = "") -> Dict[str, Any]:
    uid = str(uuid.uuid4())
    acc = generate_account_number()
    ph = hash_password(password)
    c = DB.cursor()
    c.execute(
        "INSERT INTO users(id,email,password_hash,full_name,phone,account,balance,settings) VALUES (?,?,?,?,?,?,?,?)",
        (uid, email, ph, full_name, "", acc, 0.0, "{}"),
    )
    DB.commit()
    return {"id": uid, "email": email, "account": acc, "full_name": full_name}


def user_get_by_email(email: str):
    c = DB.cursor()
    c.execute("SELECT id,email,password_hash,full_name,phone,account,balance FROM users WHERE email = ?", (email,))
    r = c.fetchone()
    if not r:
        return None

    bal = r[6]
    try:
        bal = float(bal) if bal is not None else 0.0
    except:
        bal = 0.0

    return {
        "id": r[0],
        "email": r[1],
        "password_hash": r[2],
        "full_name": r[3],
        "phone": r[4],
        "account": r[5],
        "balance": bal,
    }


def user_update_balance(user_id: str, new_balance: float):
    c = DB.cursor()
    c.execute("UPDATE users SET balance = ? WHERE id = ?", (round(float(new_balance), 2), user_id))
    DB.commit()


def user_update_profile(user_id: str, full_name: str, phone: str):
    c = DB.cursor()
    c.execute("UPDATE users SET full_name = ?, phone = ? WHERE id = ?", (full_name, phone, user_id))
    DB.commit()


def user_change_password(user_id: str, new_password: str):
    c = DB.cursor()
    c.execute("UPDATE users SET password_hash = ? WHERE id = ?", (hash_password(new_password), user_id))
    DB.commit()


def user_get_settings(user_id: str) -> Dict[str, str]:
    c = DB.cursor()
    c.execute("SELECT settings FROM users WHERE id = ?", (user_id,))
    row = c.fetchone()
    raw = row[0] if row and row[0] else "{}"
    defaults = {"theme": "light", "language": "Русский", "sound": "on"}

    try:
        import json
        parsed = json.loads(raw)
        if isinstance(parsed, dict):
            defaults.update({k: v for k, v in parsed.items() if isinstance(v, str)})
    except Exception:
        pass

    return defaults


def user_save_settings(user_id: str, settings: Dict[str, str]):
    import json
    current = user_get_settings(user_id)
    current.update(settings or {})
    c = DB.cursor()
    c.execute("UPDATE users SET settings = ? WHERE id = ?", (json.dumps(current, ensure_ascii=False), user_id))
    DB.commit()


def mk_op(user_id: str, op_type: str, amount: float, currency="RUB", title="", details="") -> None:
    c = DB.cursor()
    c.execute(
        "INSERT INTO ops(id,user_id,date,type,amount,currency,title,details) VALUES (?,?,?,?,?,?,?,?)",
        (str(uuid.uuid4()), user_id, now_ts(), op_type, round(float(amount), 2), currency, title, details),
    )
    DB.commit()


def ops_for_user(user_id: str, limit: int = 1000):
    c = DB.cursor()
    c.execute(
        "SELECT id,date,type,amount,currency,title,details FROM ops WHERE user_id = ? ORDER BY date DESC LIMIT ?",
        (user_id, limit),
    )
    rows = c.fetchall()
    return [
        {
            "id": r[0],
            "date": r[1],
            "type": r[2],
            "amount": float(r[3]),
            "currency": r[4],
            "title": r[5],
            "details": r[6],
        }
        for r in rows
    ]


def filter_ops(
    ops: List[Dict[str, Any]],
    query: str = "",
    date_from: str = "",
    date_to: str = "",
    op_type: str = "all",
    min_amount: str = "",
    max_amount: str = "",
) -> List[Dict[str, Any]]:
    q = (query or "").strip().lower()
    df = safe_date((date_from or "").strip())
    dt = safe_date((date_to or "").strip())
    min_val = safe_float((min_amount or "").strip(), None)
    max_val = safe_float((max_amount or "").strip(), None)

    filtered = []

    for op in ops:
        op_date_raw = (op.get("date") or "")[:10]
        op_date = safe_date(op_date_raw)
        op_type_raw = op.get("type", "")
        op_title = op.get("title") or ""
        op_details = op.get("details") or ""
        op_currency = op.get("currency") or ""
        op_amount = safe_float(op.get("amount"), 0.0)

        haystack = " ".join(
            [
                op_date_raw,
                op_type_raw,
                human_op_type(op_type_raw),
                op_title,
                op_details,
                op_currency,
                f"{op_amount}",
            ]
        ).lower()

        if q and q not in haystack:
            continue
        if op_type and op_type != "all" and op_type_raw != op_type:
            continue
        if df and op_date and op_date < df:
            continue
        if dt and op_date and op_date > dt:
            continue

        abs_amount = abs(op_amount)
        if min_val is not None and abs_amount < min_val:
            continue
        if max_val is not None and abs_amount > max_val:
            continue

        filtered.append(op)

    return filtered


def summarize_filtered_ops(ops: List[Dict[str, Any]]) -> Dict[str, float]:
    income_total = 0.0
    expense_total = 0.0

    for op in ops:
        amount = safe_float(op.get("amount"), 0.0)
        op_type = op.get("type", "")

        if op_type in ["income", "deposit_interest"]:
            income_total += abs(amount)
        elif op_type in ["expense", "transfer", "deposit_open"]:
            expense_total += abs(amount)

    return {
        "count": len(ops),
        "income_total": round(income_total, 2),
        "expense_total": round(expense_total, 2),
    }


def deposits_list_for_user(user_id: str) -> List[Dict[str, Any]]:
    c = DB.cursor()
    c.execute("SELECT id,name,amount,rate,opened,ends,active FROM deposits WHERE user_id = ?", (user_id,))
    rows = c.fetchall()
    out = []
    for r in rows:
        out.append(
            {
                "id": r[0],
                "name": r[1],
                "amount": float(r[2]),
                "rate": float(r[3]),
                "opened": r[4],
                "ends": r[5],
                "active": bool(r[6]),
            }
        )
    return out


def create_deposit(user_id: str, name: str, amount: float, rate: float, term_months: int):
    opened = datetime.date.today()
    ends = opened + datetime.timedelta(days=term_months * 30)
    did = str(uuid.uuid4())
    c = DB.cursor()
    c.execute(
        "INSERT INTO deposits(id,user_id,name,amount,rate,opened,ends,active) VALUES (?,?,?,?,?,?,?,?)",
        (did, user_id, name, round(float(amount), 2), float(rate), opened.isoformat(), ends.isoformat(), 1),
    )
    DB.commit()
    mk_op(user_id, "deposit_open", amount, title=f"Открытие вклада: {name}", details=f"term:{term_months}")


