    def flatten_assistant_nodes(nodes, path_titles=None):
        path_titles = path_titles or []
        out = []
        for node in nodes:
            current_path = path_titles + [node["title"]]
            entry = {**node, "path_titles": current_path}
            out.append(entry)
            if node.get("children"):
                out.extend(flatten_assistant_nodes(node["children"], current_path))
        return out

    def get_nodes_by_path(path_ids):
        nodes = ASSISTANT_TREE
        current = None
        for pid in path_ids:
            current = next((n for n in nodes if n["id"] == pid), None)
            if not current:
                return None, []
            nodes = current.get("children", [])
        return current, nodes

    def get_node_ids_by_path_titles(path_titles):
        ids = []
