    def flatten_assistant_nodes(nodes, path_titles=None):
        path_titles = path_titles or []
        out = []
        for node in nodes:
            current_path = path_titles + [node["title"]]
            entry = {**node, "path_titles": current_path}
            out.append(entry)
            if node.get("children"):
                out.extend(flatten_assistant_nodes(node["children"], current_path))
        return out

    def get_nodes_by_path(path_ids):
        nodes = translate_tree_node(ASSISTANT_ROOT_TREE)
        current = None
        for pid in path_ids:
            current = next((n for n in nodes if n["id"] == pid), None)
            if not current:
                return None, []
            nodes = current.get("children", [])
        return current, nodes

    def get_node_ids_by_path_titles(path_titles):
        ids = []
        nodes = translate_tree_node(ASSISTANT_ROOT_TREE)
        for title in path_titles:
            current = next((n for n in nodes if n["title"] == title), None)
            if not current:
                break
            ids.append(current["id"])
            nodes = current.get("children", [])
        return ids

    def open_assistant_node(node_id: str):
        flat = flatten_assistant_nodes(translate_tree_node(ASSISTANT_ROOT_TREE))
        target = next((n for n in flat if n["id"] == node_id), None)
        if not target:
            return
        ids = get_node_ids_by_path_titles(target["path_titles"])
        assistant_state["path"] = (
            ids[:-1]
            if target.get("instructions") or not target.get("children")
            else ids
        )
        assistant_state["selected"] = target["id"]

