    def rank_assistant_matches(query: str):
        query_words = [w for w in re.split(r"\s+", query.lower()) if w]
        matches = []
        for node in flatten_assistant_nodes(translate_tree_node(ASSISTANT_ROOT_TREE)):
            hay_parts = [
                node.get("title", ""),
                node.get("description", ""),
                " ".join(node.get("keywords", [])),
                " ".join(node.get("instructions", [])),
            ]
            hay = " ".join(hay_parts).lower()
            score = 0
            if query in hay:
                score += 10
            for word in query_words:
                if word in hay:
                    score += 3
            if query in node.get("title", "").lower():
                score += 6
            if score > 0 and (node.get("instructions") or node.get("children")):
                matches.append((score, node))
        matches.sort(
            key=lambda item: (
                -item[0],
                len(item[1].get("path_titles", [])),
                item[1]["title"],
            )
        )
        unique = []
        seen = set()
        for score, node in matches:
            if node["id"] in seen:
                continue
            seen.add(node["id"])
            unique.append(node)
        return unique

    def build_related_topic_suggestions(query: str):
        all_nodes = [
            n
            for n in flatten_assistant_nodes(translate_tree_node(ASSISTANT_ROOT_TREE))
            if n.get("children") or n.get("instructions")
        ]
        query_words = [w for w in re.split(r"\s+", query.lower()) if len(w) > 2]
        scored = []
        for node in all_nodes:
            hay = " ".join(
                [
                    node.get("title", ""),
                    node.get("description", ""),
                    " ".join(node.get("keywords", [])),
                ]
            ).lower()
            score = sum(1 for word in query_words if word in hay)
            if score > 0:
                scored.append((score, node))
        if not scored:
            return [n for n in all_nodes if len(n.get("path_titles", [])) == 1][:4]
        scored.sort(
            key=lambda item: (
                -item[0],
                len(item[1].get("path_titles", [])),
                item[1]["title"],
            )
        )
        return [node for _, node in scored[:4]]

